from backend.app.baseline.models import ConfidenceLevel, EvidenceItem, HypothesisRanking
from backend.app.investigation.states import InvestigationState


# ==============================================================================
# 1. EXECUTION BUDGETS
# ==============================================================================

class ExecutionBudget(BaseModel):
    """Hard boundaries enforced on the investigation execution loop."""

    max_steps: int = Field(default=8, ge=1, description="Maximum agent state transitions allowed")
    max_llm_calls: int = Field(default=2, ge=1, description="Maximum calls to LLM completion APIs")
    max_tool_calls: int = Field(default=10, ge=1, description="Maximum telemetry tool executions")
    max_evidence_items: int = Field(default=50, ge=1, description="Maximum total evidence pieces to process")
    max_tokens: int = Field(default=12000, ge=100, description="Maximum cumulative tokens permitted")
    max_seconds: float = Field(default=120.0, ge=1.0, description="Wall-clock execution timeout in seconds")


class BudgetConsumption(BaseModel):
    """Cumulative resource consumption tracked across the investigation loop."""

    steps: int = Field(default=0, ge=0)
    llm_calls: int = Field(default=0, ge=0)
    tool_calls: int = Field(default=0, ge=0)
    evidence_items: int = Field(default=0, ge=0)
    tokens_used: int = Field(default=0, ge=0)
    duration_seconds: float = Field(default=0.0, ge=0.0)

    def check_exceeded(self, budget: ExecutionBudget) -> Tuple[bool, Optional[str]]:
        """Check if any hard budget boundary has been breached.
        
        Returns:
            (True, reason_string) if exceeded, (False, None) otherwise.
        """
        if self.steps >= budget.max_steps:
            return True, f"Budget exceeded: max_steps ({self.steps} >= {budget.max_steps})"
        if self.llm_calls >= budget.max_llm_calls:
            return True, f"Budget exceeded: max_llm_calls ({self.llm_calls} >= {budget.max_llm_calls})"
        if self.tool_calls >= budget.max_tool_calls:
            return True, f"Budget exceeded: max_tool_calls ({self.tool_calls} >= {budget.max_tool_calls})"
        if self.tokens_used >= budget.max_tokens:
            return True, f"Budget exceeded: max_tokens ({self.tokens_used} >= {budget.max_tokens})"
        if self.duration_seconds >= budget.max_seconds:
            return True, f"Budget exceeded: max_seconds ({self.duration_seconds:.1f}s >= {budget.max_seconds}s)"
        return False, None


# ==============================================================================
# 2. LLM HYPOTHESIS PROPOSALS (STRUCTURED OUTPUT SCHEMAS)
# ==============================================================================

class HypothesisProposal(BaseModel):
    """Individual root cause hypothesis proposal generated by the LLM."""

    root_cause: str = Field(
        ...,
        min_length=3,
        max_length=128,
        description="Standardized or descriptive root cause identifier (e.g., database_connection_pool_exhaustion)",
    )
    title: str = Field(
        ...,
        min_length=3,
        max_length=200,
        description="Concise human-readable title",
    )
    affected_service: Optional[str] = Field(
        default=None,
        description="Service or component suspected to be failing",
    )
    supporting_evidence_refs: List[str] = Field(
        default_factory=list,
        description="List of specific evidence references supporting this hypothesis",
    )
    contradicting_evidence_refs: List[str] = Field(
        default_factory=list,
        description="List of specific evidence references that contradict or weaken this hypothesis",
    )
    uncertainty: Optional[str] = Field(
        default=None,
        description="Missing information or uncertainty caveats",
    )
    causal_explanation: str = Field(
        ...,
        min_length=10,
        max_length=2000,
        description="Clear technical explanation of the causal mechanism leading to the observed failure",
    )


class HypothesisGenerationOutput(BaseModel):
    """Enforce structured JSON output format for LLM hypothesis generation."""

    hypotheses: List[HypothesisProposal] = Field(
        default_factory=list,
        description="List of candidate root cause hypotheses (maximum 5)",
    )
    investigation_summary: Optional[str] = Field(
        default=None,
        description="High-level synthesis of observed telemetry",
    )


# ==============================================================================
# 3. RETRIEVED KNOWLEDGE SOURCES (RAG)
# ==============================================================================

class RetrievedSourceItem(BaseModel):
    """Runbook or document chunk retrieved via RAG during incident investigation."""

    doc_id: str = Field(..., description="Document identifier")
    chunk_id: Optional[str] = Field(default=None, description="Specific chunk identifier")
    title: str = Field(..., description="Runbook or document title")
    source: str = Field(default="docs", description="Document source or storage type")
    service: str = Field(default="all", description="Target service scope")
    excerpt: str = Field(..., description="Retrieved excerpt from the document")
    similarity_score: float = Field(default=0.0, description="Cosine similarity score (0.0 to 1.0)")
    rank: int = Field(default=1, description="1-indexed retrieval ranking")
    included_in_context: bool = Field(default=True, description="Whether this excerpt was included in the LLM prompt context")
    why_relevant: Optional[str] = Field(default=None, description="Explanation of why this document is relevant to the incident")


# ==============================================================================
# 4. FINAL INVESTIGATION RESULT
# ==============================================================================

class InvestigationResult(BaseModel):
    """Durable, structured outcome of a Sherlog incident investigation."""

    incident_id: str = Field(..., description="Target incident identifier")
    investigation_id: str = Field(..., description="Unique investigation tracking ID")
    status: InvestigationState = Field(..., description="Final investigation lifecycle state")
    has_sufficient_evidence: bool = Field(..., description="True if evidence met confidence threshold")
    root_cause: Optional[str] = Field(default=None, description="Identified root cause identifier")
    confidence: ConfidenceLevel = Field(..., description="Confidence level derived deterministically")
    ranked_hypotheses: List[HypothesisRanking] = Field(
        default_factory=list,
        description="Ranked hypotheses with deterministic scores and supporting evidence",
    )
    evidence_count: int = Field(default=0, description="Total evidence items evaluated")
    evidence_references: List[str] = Field(
        default_factory=list,
        description="Summary list of evidence names/queries evaluated",
    )
    retrieved_sources: List[RetrievedSourceItem] = Field(
        default_factory=list,
        description="Runbooks or document chunks retrieved and evaluated during investigation",
    )
    retrieval_status: str = Field(
        default="NOT_ATTEMPTED",
        description="Outcome status of RAG retrieval: SUCCESS, NO_DOCUMENTS_FOUND, DISABLED, or FAILED",
    )
    tool_executions: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Log of executed tools with status and latency",
    )
    budget_consumed: BudgetConsumption = Field(
        default_factory=BudgetConsumption,
        description="Resource consumption metrics",
    )
    source: str = Field(
        default="llm",
        description="Reasoning origin (llm, baseline_fallback, insufficient_evidence)",
    )
    summary: str = Field(..., description="Diagnostic summary statement")
    started_at: datetime = Field(..., description="Investigation start timestamp")
    completed_at: Optional[datetime] = Field(default=None, description="Completion timestamp")
    termination_reason: Optional[str] = Field(default=None, description="Termination explanation if stopped early")
    error_message: Optional[str] = Field(default=None, description="Sanitized error details if failed")

